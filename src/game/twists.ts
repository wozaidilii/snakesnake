export function assemble(baked: Level[]): Level[] {
  const out: Level[] = [];
  for (let tier = 1; tier <= 10; tier++) {
    const id = String(tier);
    out.push(...baked.filter((level) => level.rank === id));
    out.push(...TWISTS.filter((level) => level.rank === id));
  }
  return out;
}
