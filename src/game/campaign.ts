import type { Level, WorldId } from "./types";

// 咕咕归巢的五张手绘地图（来源：gugu_maps.py）。
// 换算：* → X 小屋；g/y 按钮与门 → B/D（太阳）；p 按钮与门 → b/d（月亮）；虫子坐标 → 0 起的数字。
function farm(n: number, world: WorldId, name: string, rows: string[], insight: string, hints: string[], difficulty: Level["difficulty"], requires: Level["requires"] = [], tutorial = false): Level {
  return { id: `gugu-${String(n).padStart(2, "0")}`, world, name, rows, gentle: true, noReverse: true,
    hint: insight, insight, hints, difficulty, requires, tutorial, challenge: difficulty === 5,
    rank: String(["soil", "runnel", "nursery", "shear", "orchard", "pond"].indexOf(world) + 1) };
}

